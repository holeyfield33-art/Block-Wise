"""Generate Python from a validated plan without importing or running generated code."""

import ast
import copy
import json
from pathlib import Path

from .schema import ScoreError, expression, validate_score

AUG_OPERATORS = {"+=": ast.Add, "-=": ast.Sub, "*=": ast.Mult, "/=": ast.Div, "//=": ast.FloorDiv, "%=": ast.Mod,
                 "**=": ast.Pow, "@=": ast.MatMult, "&=": ast.BitAnd, "|=": ast.BitOr, "^=": ast.BitXor,
                 "<<=": ast.LShift, ">>=": ast.RShift}

HOLE_PREFIX = "TODO:"
DOCSTRING = "Generated by Blockwise. Verify behavior before use."


def compile_nodes(nodes):
    statements = []
    for node in nodes:
        kind = node["kind"]
        if kind in ("call", "validate"):
            statements.append(ast.Expr(value=expression(node["expression"], kind)))
        elif kind == "return":
            statements.append(ast.Return(value=expression(node["expression"], kind)))
        elif kind == "raise":
            statements.append(ast.Raise(exc=expression(node["expression"], kind), cause=None))
        elif kind == "assign" and node.get("operator", "=") != "=":
            statements.append(ast.AugAssign(target=ast.Name(id=node["target"], ctx=ast.Store()),
                                            op=AUG_OPERATORS[node["operator"]](), value=expression(node["expression"], kind)))
        elif kind == "assign":
            statements.append(ast.Assign(targets=[ast.Name(id=node["target"], ctx=ast.Store())],
                                         value=expression(node["expression"], kind)))
        elif kind == "while":
            statements.append(ast.While(test=expression(node["condition"], kind),
                                        body=compile_nodes(node["body"]) or [ast.Pass()], orelse=[]))
        elif kind == "break":
            statements.append(ast.Break())
        elif kind == "continue":
            statements.append(ast.Continue())
        elif kind == "branch":
            statements.append(ast.If(test=expression(node["condition"], kind),
                                     body=compile_nodes(node["body"]) or [ast.Pass()],
                                     orelse=compile_nodes(node["otherwise"])))
        elif kind == "loop":
            statements.append(ast.For(target=ast.Name(id=node["target"], ctx=ast.Store()),
                                      iter=expression(node["iterable"], kind),
                                      body=compile_nodes(node["body"]) or [ast.Pass()], orelse=[]))
        elif kind == "try":
            handler = ast.ExceptHandler(type=expression(node["exception"], kind), name=node["alias"] or None,
                                        body=compile_nodes(node["handler"]) or [ast.Pass()])
            statements.append(ast.Try(body=compile_nodes(node["body"]) or [ast.Pass()], handlers=[handler],
                                      orelse=[], finalbody=compile_nodes(node["finally"])))
        elif kind == "with":
            alias = ast.Name(id=node["alias"], ctx=ast.Store()) if node["alias"] else None
            statements.append(ast.With(items=[ast.withitem(context_expr=expression(node["context"], kind), optional_vars=alias)],
                                       body=compile_nodes(node["body"]) or [ast.Pass()]))
        elif kind == "hole":
            statements.append(ast.Raise(exc=ast.Call(func=ast.Name(id="NotImplementedError", ctx=ast.Load()),
                                                     args=[ast.Constant(HOLE_PREFIX + node["label"])], keywords=[]), cause=None))
    return statements


# f-strings are rendered here rather than by ast.unparse: CPython 3.12.0-3.12.8 and
# 3.13.0-3.13.2 reuse the outer quote inside {...} (f'{d['k']}'), which is a syntax
# error on Python 3.11, so generated code depended on the exact interpreter. These
# rules follow Python 3.11's unparser, which later releases match again.
_QUOTES = ("'", '"', '"""', "'''")


def _literal(text, quotes, escape_whitespace):
    """Escape one f-string part and narrow the quote styles that can enclose it."""
    def escape(char):
        if not escape_whitespace and char in "\n\t":
            return char
        if char == "\\" or not char.isprintable():
            return char.encode("unicode_escape").decode("ascii")
        return char

    escaped = "".join(map(escape, text))
    possible = [q for q in quotes if len(q) == 3] if "\n" in escaped else list(quotes)
    possible = [q for q in possible if q not in escaped]
    if not possible:
        if not escape_whitespace:
            raise ScoreError("An f-string uses every kind of quote; move part of it into a variable")
        literal = repr(text)
        return literal[1:-1], [next((q for q in quotes if literal[0] in q), literal[0])]
    if escaped:
        possible.sort(key=lambda q: q[0] == escaped[-1])
        if possible[0][0] == escaped[-1]:
            escaped = escaped[:-1] + "\\" + escaped[-1]
    return escaped, possible


def _field(value):
    """One {expression!conversion:spec} replacement field."""
    source = unparse(value.value)
    if "\\" in source:
        raise ScoreError("Backslashes are not allowed inside f-string {...}; move that part into a variable")
    text = "{" + (" " if source.startswith("{") else "") + source
    if value.conversion != -1:
        text += "!" + chr(value.conversion)
    if value.format_spec is not None:
        text += ":" + "".join(_part(spec) for spec in value.format_spec.values)
    return text + "}"


def _part(value):
    if isinstance(value, ast.Constant):
        return value.value.replace("{", "{{").replace("}", "}}")
    return _field(value)


def _fstring(node):
    quotes, parts = _QUOTES, []
    for value in node.values:
        text, quotes = _literal(_part(value), quotes, isinstance(value, ast.Constant))
        parts.append(text)
    return f"f{quotes[0]}{''.join(parts)}{quotes[0]}"


class _Placeholders(ast.NodeTransformer):
    """Swap each outermost f-string for a unique name; nested ones are rendered by _fstring."""

    def __init__(self):
        self.rendered = {}

    def visit_JoinedStr(self, node):
        name = f"__blockwise_fstring_{len(self.rendered)}__"
        self.rendered[name] = _fstring(node)
        return ast.copy_location(ast.Name(id=name, ctx=ast.Load()), node)


def unparse(node):
    """ast.unparse with interpreter-independent f-strings (see _QUOTES)."""
    placeholders = _Placeholders()
    text = ast.unparse(placeholders.visit(copy.deepcopy(node)))
    for name, rendered in placeholders.rendered.items():
        text = text.replace(name, rendered)
    return text


def pep8_join(statements):
    """Unparse top-level statements with two blank lines before each function (PEP 8)."""
    source = ""
    for index, statement in enumerate(statements):
        # Unparsing the first statement inside a Module keeps a docstring as """...""".
        text = unparse(ast.Module(body=[statement], type_ignores=[]) if index == 0 else statement)
        if source:
            source += "\n\n\n" if isinstance(statement, (ast.FunctionDef, ast.If)) else "\n"
        source += text
    return source + "\n"


def compile_score(score):
    score = validate_score(score)
    sources = {}
    for module in score["modules"]:
        body = [ast.Expr(value=ast.Constant(DOCSTRING))]
        for imported in module["imports"]:
            body.extend(ast.parse(imported).body)
        for constant in module["constants"]:
            body.append(ast.Assign(targets=[ast.Name(id=constant["name"], ctx=ast.Store())],
                                   value=expression(constant["value"], "constant")))
        for function in module["functions"]:
            parameters = [ast.arg(arg=item["name"], annotation=expression(item["type"], "type"))
                          for item in function["parameters"]]
            defaults = [expression(item["default"], "default") for item in function["parameters"] if "default" in item]
            arguments = ast.arguments(posonlyargs=[], args=parameters, vararg=None, kwonlyargs=[],
                                      kw_defaults=[], kwarg=None, defaults=defaults)
            statements = compile_nodes(function["body"])
            if function["requirements"]:
                statements.insert(0, ast.Expr(value=ast.Constant("Requirements:\n" + "\n".join(function["requirements"]))))
            body.append(ast.FunctionDef(name=function["name"], args=arguments, body=statements or [ast.Pass()],
                                        decorator_list=[], returns=expression(function["returns"], "returns")))
        if "entry" in module:
            body.append(ast.If(test=ast.Compare(left=ast.Name(id="__name__", ctx=ast.Load()), ops=[ast.Eq()],
                                                comparators=[ast.Constant("__main__")]),
                               body=compile_nodes(module["entry"]) or [ast.Pass()], orelse=[]))
        tree = ast.fix_missing_locations(ast.Module(body=body, type_ignores=[]))
        source = pep8_join(tree.body)
        compile(source, module["path"], "exec")
        sources[module["path"]] = source
    return sources


def handoff(score, sources):
    return """# Implement this Python template

The accompanying plan.json is the exact structural plan.

Fill only the TODO placeholders. Preserve module paths, function
signatures, imports, required expressions, branch/loop nesting and statement
order. Each hole lists its allowed calls. If a requirement cannot be met within
this plan, explain the conflict and propose an explicit plan revision.
Do not silently remove a check or widen the allowed calls/imports.

Run behavioral tests for the stated requirements. The plan checker compares
syntax; passing it does not prove behavior, security or correctness.

## Requirements

""" + "\n".join("- " + requirement for requirement in score["requirements"]
                     + [requirement for module in score["modules"] for function in module["functions"]
                        for requirement in function["requirements"]]) + "\n\n## Exact scaffold\n\n" + "\n".join(
        f"### {path}\n\n```python\n{source}```\n" for path, source in sources.items())


def write_project(score, output, audio=False):
    """Create a fresh bundle: repo/, plan.json, AGENT_HANDOFF.md and, optionally, a WAV of the plan."""

    score = validate_score(score)
    sources = compile_score(score)
    output = Path(output)
    if output.exists():
        raise ScoreError("Build output must be a new directory; existing projects are never replaced")
    output.mkdir(parents=True)
    repository = output / "repo"
    repository.mkdir()
    for relative, source in sources.items():
        target = repository / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(source, encoding="utf-8", newline="\n")
    (output / "plan.json").write_text(json.dumps(score, indent=2, ensure_ascii=False), encoding="utf-8")
    (output / "AGENT_HANDOFF.md").write_text(handoff(score, sources), encoding="utf-8")
    result = {"files": list(sources), "repo": str(repository), "handoff": str(output / "AGENT_HANDOFF.md")}
    if audio:
        from .audio import render_score

        result["audio_events"] = len(render_score(score, output / "plan.wav"))
    return result
