"""Generate Python from a validated plan without importing or running generated code."""

import ast
import json
from pathlib import Path

from .schema import ScoreError, expression, validate_score

HOLE_PREFIX = "TODO:"
DOCSTRING = "Generated by Blockwise. Verify behavior before use."


def compile_nodes(nodes):
    statements = []
    for node in nodes:
        kind = node["kind"]
        if kind in ("call", "validate"):
            statements.append(ast.Expr(value=expression(node["expression"], kind)))
        elif kind == "return":
            statements.append(ast.Return(value=expression(node["expression"], kind)))
        elif kind == "raise":
            statements.append(ast.Raise(exc=expression(node["expression"], kind), cause=None))
        elif kind == "assign":
            statements.append(ast.Assign(targets=[ast.Name(id=node["target"], ctx=ast.Store())],
                                         value=expression(node["expression"], kind)))
        elif kind == "branch":
            statements.append(ast.If(test=expression(node["condition"], kind),
                                     body=compile_nodes(node["body"]) or [ast.Pass()],
                                     orelse=compile_nodes(node["otherwise"])))
        elif kind == "loop":
            statements.append(ast.For(target=ast.Name(id=node["target"], ctx=ast.Store()),
                                      iter=expression(node["iterable"], kind),
                                      body=compile_nodes(node["body"]) or [ast.Pass()], orelse=[]))
        elif kind == "hole":
            statements.append(ast.Raise(exc=ast.Call(func=ast.Name(id="NotImplementedError", ctx=ast.Load()),
                                                     args=[ast.Constant(HOLE_PREFIX + node["label"])], keywords=[]), cause=None))
    return statements


def pep8_join(statements):
    """Unparse top-level statements with two blank lines before each function (PEP 8)."""
    source = ""
    for index, statement in enumerate(statements):
        # Unparsing the first statement inside a Module keeps a docstring as """...""".
        text = ast.unparse(ast.Module(body=[statement], type_ignores=[]) if index == 0 else statement)
        if source:
            source += "\n\n\n" if isinstance(statement, ast.FunctionDef) else "\n"
        source += text
    return source + "\n"


def compile_score(score):
    score = validate_score(score)
    sources = {}
    for module in score["modules"]:
        body = [ast.Expr(value=ast.Constant(DOCSTRING))]
        for imported in module["imports"]:
            body.extend(ast.parse(imported).body)
        for function in module["functions"]:
            parameters = [ast.arg(arg=item["name"], annotation=expression(item["type"], "type"))
                          for item in function["parameters"]]
            arguments = ast.arguments(posonlyargs=[], args=parameters, vararg=None, kwonlyargs=[],
                                      kw_defaults=[], kwarg=None, defaults=[])
            statements = compile_nodes(function["body"])
            if function["requirements"]:
                statements.insert(0, ast.Expr(value=ast.Constant("Requirements:\n" + "\n".join(function["requirements"]))))
            body.append(ast.FunctionDef(name=function["name"], args=arguments, body=statements or [ast.Pass()],
                                        decorator_list=[], returns=expression(function["returns"], "returns")))
        tree = ast.fix_missing_locations(ast.Module(body=body, type_ignores=[]))
        source = pep8_join(tree.body)
        compile(source, module["path"], "exec")
        sources[module["path"]] = source
    return sources


def handoff(score, sources):
    return """# Implement this Python template

The accompanying plan.json is the exact structural plan.

Fill only the TODO placeholders. Preserve module paths, function
signatures, imports, required expressions, branch/loop nesting and statement
order. Each hole lists its allowed calls. If a requirement cannot be met within
this plan, explain the conflict and propose an explicit plan revision.
Do not silently remove a check or widen the allowed calls/imports.

Run behavioral tests for the stated requirements. The plan checker compares
syntax; passing it does not prove behavior, security or correctness.

## Requirements

""" + "\n".join("- " + requirement for requirement in score["requirements"]
                     + [requirement for module in score["modules"] for function in module["functions"]
                        for requirement in function["requirements"]]) + "\n\n## Exact scaffold\n\n" + "\n".join(
        f"### {path}\n\n```python\n{source}```\n" for path, source in sources.items())


def write_project(score, output, audio=False):
    """Create a fresh bundle: repo/, plan.json, AGENT_HANDOFF.md and, optionally, a WAV of the plan."""

    score = validate_score(score)
    sources = compile_score(score)
    output = Path(output)
    if output.exists():
        raise ScoreError("Build output must be a new directory; existing projects are never replaced")
    output.mkdir(parents=True)
    repository = output / "repo"
    repository.mkdir()
    for relative, source in sources.items():
        target = repository / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(source, encoding="utf-8", newline="\n")
    (output / "plan.json").write_text(json.dumps(score, indent=2, ensure_ascii=False), encoding="utf-8")
    (output / "AGENT_HANDOFF.md").write_text(handoff(score, sources), encoding="utf-8")
    result = {"files": list(sources), "repo": str(repository), "handoff": str(output / "AGENT_HANDOFF.md")}
    if audio:
        from .audio import render_score

        result["audio_events"] = len(render_score(score, output / "plan.wav"))
    return result
