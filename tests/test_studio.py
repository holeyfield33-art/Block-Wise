"""Studio data stays valid and in sync; the browser page matches the Python compiler exactly."""

import json
import os
import shutil
import subprocess
from pathlib import Path

import pytest

from blockwise.cli import main
from blockwise.compiler import compile_score
from blockwise.schema import validate_score

ROOT = Path(__file__).resolve().parents[1]
STUDIO = ROOT / "studio"


def load_js_array(path, name):
    text = path.read_text(encoding="utf-8")
    start = text.index(f"window.{name} = ") + len(f"window.{name} = ")
    return json.loads(text[start:text.rindex(";")])


LESSONS = load_js_array(STUDIO / "lessons.js", "BLOCKWISE_LESSONS")


def without_module_docstring(source):
    """The Studio preview omits the generated module docstring; everything else must match exactly."""
    assert source.startswith('"""Generated by Blockwise.')
    return source.split("\n", 1)[1].lstrip("\n")


@pytest.mark.parametrize("lesson", LESSONS, ids=[lesson["id"] for lesson in LESSONS])
def test_lesson_plans_are_valid_and_compile(lesson):
    for key in ("starter", "solution"):
        compile_score(validate_score(lesson[key]))
    assert len(lesson["steps"]) >= 3 and lesson["goal"] and lesson["explain"]
    starter = {(m["path"], f["name"]) for m in lesson["starter"]["modules"] for f in m["functions"]}
    solution = {(m["path"], f["name"]) for m in lesson["solution"]["modules"] for f in m["functions"]}
    assert starter == solution


def test_studio_presets_file_is_in_sync(tmp_path):
    out = tmp_path / "presets.js"
    assert main(["export-presets", "--out", str(out)]) == 0
    assert out.read_text() == (STUDIO / "presets.js").read_text(), "run: blockwise export-presets --out studio/presets.js"


@pytest.fixture(scope="module")
def e2e(tmp_path_factory):
    node = shutil.which("node")
    if not node:
        pytest.skip("node not installed")
    npm_root = subprocess.run(["npm", "root", "-g"], capture_output=True, text=True, check=False).stdout.strip()
    if not (Path(npm_root) / "playwright").exists():
        pytest.skip("playwright (npm) not installed")
    out = tmp_path_factory.mktemp("e2e")
    proc = subprocess.run([node, str(ROOT / "tests" / "studio_e2e.cjs"), str(out)], capture_output=True, text=True,
                          timeout=240, env={**os.environ, "NODE_PATH": npm_root}, check=False)
    assert proc.returncode == 0, proc.stderr[-3000:]
    return json.loads((out / "studio_e2e.json").read_text())


def test_studio_runs_without_errors_and_lessons_check(e2e):
    assert e2e["errors"] == []
    assert all(r == {"guided_not_yet": True, "solution_correct": True} for r in e2e["lessons"].values())
    ui = e2e["ui"]
    assert ui["clicked_lesson_correct"] and ui["bad_name_flagged"] and ui["preset_inserted"] and ui["sparse_plan_renders"]
    assert "Not yet" in ui["wrong_condition_message"] and "age >= 18" not in ui["wrong_condition_message"]
    assert "deep nesting" in ui["advisor_text"]
    assert ui["phone_no_hscroll"] and ui["phone_nav_shows_code"]


@pytest.mark.parametrize("lesson", LESSONS, ids=[lesson["id"] for lesson in LESSONS])
def test_studio_python_matches_compiler(e2e, lesson):
    expected = compile_score(validate_score(lesson["solution"]))
    for path, source in e2e["generated"][lesson["id"]].items():
        assert source == without_module_docstring(expected[path]), "Studio text differs from compiler output"
