"""Studio data stays valid and in sync; the browser page matches the Python compiler exactly."""

import json
import os
import re
import shutil
import subprocess
from pathlib import Path

import pytest

from blockwise.cli import main
from blockwise.compiler import compile_score
from blockwise.schema import validate_score

ROOT = Path(__file__).resolve().parents[1]
STUDIO = ROOT / "studio"
PAGE = (STUDIO / "index.html").read_text(encoding="utf-8")


def load_js_array(path, name):
    text = path.read_text(encoding="utf-8")
    start = text.index(f"window.{name} = ") + len(f"window.{name} = ")
    return json.loads(text[start:text.rindex(";")])


LESSONS = load_js_array(STUDIO / "lessons.js", "BLOCKWISE_LESSONS")
HARNESS = re.search(r'<script type="text/x-python" id="pyHarness">\n(.*?)</script>', PAGE, re.S).group(1)
GLOSSARY = set(re.findall(r'^  \["([^"]+)", "', PAGE[PAGE.index("const GLOSSARY = ["):], re.M))


def without_module_docstring(source):
    """The Studio preview omits the generated module docstring; everything else must match exactly."""
    assert source.startswith('"""Generated by Blockwise.')
    return source.split("\n", 1)[1].lstrip("\n")


def run_harness(files, tests, root):
    """Run the Studio's in-browser test harness with CPython instead of Pyodide."""
    scope = {"REQ": json.dumps({"files": files, "tests": tests, "root": str(root)})}
    exec(compile(HARNESS, "pyHarness", "exec"), scope)
    return json.loads(scope["RESULT"])


@pytest.mark.parametrize("lesson", LESSONS, ids=[lesson["id"] for lesson in LESSONS])
def test_lesson_plans_are_valid_and_compile(lesson):
    for key in ("starter", "solution"):
        compile_score(validate_score(lesson[key]))
    assert len(lesson["steps"]) >= 3 and lesson["goal"] and lesson["explain"]
    starter = {(m["path"], f["name"]) for m in lesson["starter"]["modules"] for f in m["functions"]}
    solution = {(m["path"], f["name"]) for m in lesson["solution"]["modules"] for f in m["functions"]}
    assert starter == solution
    assert set(lesson["concepts"]) <= GLOSSARY, "every lesson concept needs a glossary entry in index.html"


@pytest.mark.parametrize("lesson", LESSONS, ids=[lesson["id"] for lesson in LESSONS])
def test_lesson_tests_pass_on_solution_and_fail_on_starter(lesson, tmp_path):
    tests = lesson["tests"]
    assert len(tests) >= 2 and all("call" in t and ("expect" in t) != ("raises" in t) for t in tests)
    solved = run_harness({p: without_module_docstring(s) for p, s in compile_score(lesson["solution"]).items()}, tests, tmp_path / "s")
    assert solved["load_error"] is None
    assert [t for t in solved["tests"] if not t["ok"]] == []
    started = run_harness(compile_score(lesson["starter"]), tests, tmp_path / "g")
    assert not all(t["ok"] for t in started["tests"]), "the guided starter should not already pass every test"


def test_harness_reports_load_errors_and_try_expressions(tmp_path):
    broken = run_harness({"m.py": "def f(:\n"}, [], tmp_path / "a")
    assert broken["load_error"].startswith("SyntaxError")
    scope = {"REQ": json.dumps({"files": {"m.py": "def f(x):\n    print('hi')\n    return x * 2\n"}, "expr": "f(21)", "root": str(tmp_path / "b")})}
    exec(compile(HARNESS, "pyHarness", "exec"), scope)
    result = json.loads(scope["RESULT"])
    assert result["value"] == "42" and result["output"] == "hi\n" and not result["error"]


def test_studio_presets_file_is_in_sync(tmp_path):
    out = tmp_path / "presets.js"
    assert main(["export-presets", "--out", str(out)]) == 0
    assert out.read_text() == (STUDIO / "presets.js").read_text(), "run: blockwise export-presets --out studio/presets.js"


@pytest.fixture(scope="module")
def e2e(tmp_path_factory):
    node, npm = shutil.which("node"), shutil.which("npm")
    if not node or not npm:
        pytest.skip("node not installed")
    npm_root = os.environ.get("BLOCKWISE_NODE_PATH") or subprocess.run(
        [npm, "root", "-g"], capture_output=True, text=True, check=False).stdout.strip()
    if not (Path(npm_root) / "playwright").exists():
        pytest.skip("playwright (npm) not installed")
    out = tmp_path_factory.mktemp("e2e")
    proc = subprocess.run([node, str(ROOT / "tests" / "studio_e2e.cjs"), str(out)], capture_output=True, text=True,
                          timeout=240, env={**os.environ, "NODE_PATH": npm_root}, check=False)
    assert proc.returncode == 0, proc.stderr[-3000:]
    return json.loads((out / "studio_e2e.json").read_text())


